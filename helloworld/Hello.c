
// header files are included in order to
// define things that are external, such
// as the "Standard I/O library"
// (I/O == Input/Output)
#include <stdio.h>

// All C and C++ programs begin at the function
// named "main"
int main(int argc, char** argv)
{
   // printf is a "formatted print" function
   // that is in the standard I/O library
   printf("Hello World\n");
   return 0;
}

